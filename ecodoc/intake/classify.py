"""Распределение входящих документов: что это, какие данные можно взять,
каким формам пригодится.

Эвристика по ключевым словам текста + имени файла. Работает и без ИИ;
при `--ai` семантику уточняет анализатор (doc_type из модели).

`kind` — машинный код класса (по нему реестр источников и сверка отходов
понимают, откуда пришло значение); `project` — проектная документация
(ООС/ПМООС, ПНООЛР, НДВ, инвентаризации, рекультивация, экспертиза,
общественные обсуждения): реквизиты организаций в ней — проектировщик,
заказчик, эксперты, их нельзя принимать за реквизиты НАШЕЙ организации.
Зато по отходам и воздуху ООС — основополагающий документ: нормативы
образования, состав, класс опасности берутся оттуда.
"""
from __future__ import annotations

import re
from dataclasses import dataclass

from ecodoc.parsers.text_extract import ExtractedDoc

# машинные коды классов документов
KINDS = ("oos", "pnoolr", "ndv", "passport", "protocol_kha", "biotest", "act",
         "journal", "license", "contract", "egrul", "nvos_cert", "declaration",
         "pek_program", "pek_report", "inventory_waste", "inventory_air",
         "recultivation", "expertise", "hearings", "payment", "other")

# проектная документация: реквизиты в ней — не наши
PROJECT_KINDS = frozenset({"oos", "pnoolr", "ndv", "inventory_waste",
                           "inventory_air", "recultivation", "expertise",
                           "hearings"})


@dataclass
class DocClass:
    doc_type: str      # человекочитаемый тип документа
    data: str          # какие данные можно взять
    forms: list[str]   # каким формам пригодится
    kind: str = "other"    # машинный код (см. KINDS)
    project: bool = False  # проектная документация (реквизиты — не наши)


def _dc(doc_type: str, data: str, forms: list[str], kind: str) -> DocClass:
    return DocClass(doc_type, data, forms, kind, kind in PROJECT_KINDS)


