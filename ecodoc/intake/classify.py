# класс по машинному коду — первое правило с таким kind
_BY_KIND: dict[str, DocClass] = {}
for _pat, _cls in _RULES:
    _BY_KIND.setdefault(_cls.kind, _cls)

# правила ТОЛЬКО по имени файла (для старых записей sources.json, где текста
# уже нет; для меток «имя файла (лист N)» у паспортов). Порядок = приоритет:
# проектные — первыми, «акт» — словом (иначе ловит «характеристика»).
_NAME_RULES: list[tuple[str, str]] = [
    (r"пноолр", "pnoolr"),
    (r"(?<![а-яa-z])(пм)?оос(?![а-яa-z])|пмоос", "oos"),
    (r"(?<![а-яa-z])(ндв|пдв)(?![а-яa-z])", "ndv"),
    (r"инвентар\w*.{0,40}(выброс|источник|изав)", "inventory_air"),
    (r"инвентар", "inventory_waste"),
    (r"рекультив", "recultivation"),
    (r"экспертиз", "expertise"),
    (r"обсужден|слушан", "hearings"),
    (r"биотест|био_", "biotest"),
    (r"паспорт|п\.\s?о\.\s?о\.?|(?<![а-яa-z])поо(?![а-яa-z])", "passport"),
    (r"протокол|(?<![а-яa-z])прот\.|кха", "protocol_kha"),
    (r"журнал|1028", "journal"),
    (r"лиценз", "license"),
    (r"егрюл|егрип|устав", "egrul"),
    (r"нвос", "nvos_cert"),
    (r"деклар", "declaration"),
    (r"отч[её]т.{0,20}пэк|пэк.{0,20}отч[её]т", "pek_report"),
    (r"пэк", "pek_program"),
    (r"плат[её]ж", "payment"),
    (r"договор", "contract"),
    (r"(?<![а-яa-z])акт|справк", "act"),
]


def classify(doc: ExtractedDoc) -> DocClass:
    hay = (doc.path.name + "\n" + doc.text[:8000]).lower().replace("ё", "е")
    for pattern, dc in _RULES:
        if re.search(pattern, hay, re.S):
            return dc
    return _UNKNOWN


def classify_name(filename: str) -> DocClass:
    """Классификация только по имени файла (текст недоступен).

    Принимает и метку «имя файла (лист N)» — хвост отбрасывается."""
    name = str(filename or "").split(" (лист")[0].lower().replace("ё", "е")
    for pattern, kind in _NAME_RULES:
        if re.search(pattern, name):
            return _BY_KIND.get(kind, _UNKNOWN)
    return _UNKNOWN


def by_kind(kind: str) -> DocClass:
    """Класс по машинному коду (для реестра источников)."""
    return _BY_KIND.get(kind or "", _UNKNOWN)


def render(docs: list[ExtractedDoc]) -> str:
    """Секция отчёта intake: файл → тип → что взять → для каких форм."""
    lines = ["── Распределение файлов: что это и для чего ──"]
    for d in docs:
        c = classify(d)
        lines.append(f"  • {d.path.name}")
        lines.append(f"      тип:    {c.doc_type}")
        lines.append(f"      данные: {c.data}")
        if c.forms:
            lines.append(f"      формы:  {', '.join(c.forms)}")
        if c.project:
            lines.append("      ⚠ проектная документация: реквизиты организаций "
                         "в ней — проектировщик/заказчик, в базу не брать")
    return "\n".join(lines)
