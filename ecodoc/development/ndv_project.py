def _cfg(ctx: ReportContext) -> dict:
    extra = ctx.extra if isinstance(ctx.extra, dict) else {}
    c = extra.get("ndv")
    return c if isinstance(c, dict) else {}


def _dec(v) -> Decimal | None:
    if v in (None, ""):
        return None
    try:
        return Decimal(str(v).replace(",", ".").replace(" ", ""))
    except (InvalidOperation, ValueError):
        return None


def _fmt(v: Decimal | None, nd: int = 7) -> str:
    """Числа как в «ПДВ-Эколог»: г/с — 7 знаков, т/год — 6, запятая."""
    if v is None:
        return "—"
    s = f"{v:.{nd}f}".rstrip("0").rstrip(".")
    return (s or "0").replace(".", ",")


def sources(ctx: ReportContext) -> list[dict]:
    """ИЗАВ с полными параметрами (как их хранит инвентаризация № 871)."""
    out = []
    for s in (ctx.extra or {}).get("emission_sources", []) or []:
        if not isinstance(s, dict):
            continue
        d = {k: str(s.get(k) or "").strip() for k in
             ("number", "name", "kind", "type", "workshop", "site", "unit_number",
              "unit_name", "count", "hours_year", "height", "diameter", "speed",
              "volume", "temperature", "x1", "y1", "x2", "y2", "area_width",
              "gou", "gou_coverage", "gou_efficiency", "method", "note")}
        d["pollutants"] = [p for p in (s.get("pollutants") or []) if isinstance(p, dict)]
        out.append(d)
    return out


def _ref_pdk() -> dict[str, dict]:
    from ecodoc.core import refdata
    out = {}
    for r in refdata.substances():
        if r.get("medium") == "air":
            out[str(r.get("code"))] = r
    return out


def substances(ctx: ReportContext) -> list[dict]:
    """Сводный перечень ЗВ с ПДК/классом и суммами г/с, т/год.

    Агрегация г/с и т/год — та же, что в плане НМУ (nmu.substances), чтобы
    цифры в двух документах одного объекта совпадали.
    """
    from ecodoc.development import nmu
    ref = _ref_pdk()
    names = {}
    try:
        from ecodoc.core import refdata
        names = refdata.official_air()
    except Exception:          # справочник ставок может отсутствовать в тестах
        names = {}
    out = []
    for r in nmu.substances(ctx):
        code = str(r.get("code") or "")
        rf = ref.get(code, {})
        pdk_mr = rf.get("pdk_mr")
        pdk_ss = rf.get("pdk_ss")
        out.append({
            "code": code,
            "name": r.get("name") or names.get(code, ""),
            "pdk_mr": _fmt(_dec(pdk_mr), 5) if pdk_mr is not None else "—",
            "pdk_ss": _fmt(_dec(pdk_ss), 5) if pdk_ss is not None else "—",
            "pdk_sg": _PDK_SG.get(code, "—"),
            "obuv": _OBUV.get(code, "—"),
            "hazard": _HAZARD_CLASS.get(code, ""),
            "g_s": r.get("g_s"), "t_year": r.get("t_year"),
            "solid": code in {"0123", "0143", "0184", "0203", "0328", "0344",
                              "2902", "2908", "2909", "0703"},
            "known_pdk": code in ref or code in _OBUV,
        })
    return out


def norm_years(ctx: ReportContext) -> list[int]:
    """Годы, на которые предлагаются НДВ: extra['ndv']['years'] или 7 лет
    с отчётного (п. 9 № 581 — нормативы устанавливаются на 7 лет)."""
    cfg = _cfg(ctx)
    ys = cfg.get("years")
    if isinstance(ys, list) and ys:
        return [int(y) for y in ys]
    start = int(cfg.get("year_from") or ctx.period.year or 0)
    if not start:
        return []
    n = int(cfg.get("years_count") or 7)
    return list(range(start, start + n))


def calc_points(ctx: ReportContext, src: NdvInputs | None = None) -> list[list[str]]:
    """Расчётные точки: из выгрузки «Эколога» или из extra['ndv']['calc_points']."""
    if src and src.points_table:
        return [[("" if c is None else str(c)) for c in r] for r in src.points_table]
    rows = []
    for i, p in enumerate(_cfg(ctx).get("calc_points") or [], 1):
        if not isinstance(p, dict):
            continue
        rows.append([str(p.get("code") or i), str(p.get("x") or ""), str(p.get("y") or ""),
                     str(p.get("height") or "2"), str(p.get("kind") or ""),
                     str(p.get("comment") or "")])
    return rows


