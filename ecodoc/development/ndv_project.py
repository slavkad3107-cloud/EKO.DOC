def _kv(doc, pairs):
    t = doc.add_table(rows=0, cols=2)
    t.style = "Table Grid"
    for k, v in pairs:
        cells = t.add_row().cells
        cells[0].text = str(k)
        cells[1].text = str(v) if v else "[требуется]"


def _table(doc, header, rows, empty: str):
    from docx.shared import Pt
    if not rows:
        if empty:
            doc.add_paragraph(empty)
        return
    ncol = max(len(header) if header else 0, max(len(r) for r in rows))
    t = doc.add_table(rows=0, cols=ncol)
    t.style = "Table Grid"
    if header:
        cells = t.add_row().cells
        for i, c in enumerate(header[:ncol]):
            cells[i].text = str(c)
            for p in cells[i].paragraphs:
                for r in p.runs:
                    r.bold = True
                    r.font.size = Pt(8)
    for r in rows:
        cells = t.add_row().cells
        for i, c in enumerate(r[:ncol]):
            cells[i].text = "" if c is None else str(c)
            for p in cells[i].paragraphs:
                for rr in p.runs:
                    rr.font.size = Pt(8)
