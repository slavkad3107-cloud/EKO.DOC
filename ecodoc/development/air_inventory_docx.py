    d.h("1.2. Краткое описание видов деятельности на объекте ОНВ", 2)
    d.h("1.2.1. Краткая характеристика технологии производства и технологического оборудования объекта ОНВ", 2)
    d.p(str(c.get("production") or _req(
        "описание технологии производства, оборудования, режима работы, численности, "
        "объёмов выпуска (п. 35 «б» Порядка № 871); источник — раздел ООС/ПМООС, "
        "технологический регламент")))
    d.h("1.2.2. Сведения о сырье, материалах, топливе и выпускаемой продукции", 2)
    d.p(str(c.get("materials") or _req(
        "перечень сырья, материалов, топлива с годовым расходом и выпускаемая продукция")))
    d.h("1.2.3. Сведения о количестве, характеристиках и эффективности ГОУ", 2)
    d.typical(GOU_DEFINITION)
    if gou:
        for g in gou:
            d.p(f"– {g.get('name') or _req('тип, марка ГОУ')}: ИЗАВ № {g.get('izav', '—')}, "
                f"эффективность очистки {g.get('eff_actual') or g.get('kpd') or _req('%')} %"
                f"{'; паспорт — Приложение 5' if True else ''}.")
    elif c.get("has_gou") is False:
        d.p("Газоочистные установки на объекте ОНВ отсутствуют.")
    else:
        d.p(_req("сведения о ГОУ: наличие, тип, марка, № в реестре, КПД проектный и фактический"))
    d.h("1.2.4. Мероприятия по охране атмосферного воздуха", 2)
    d.p(str(c.get("measures") or "Мероприятия по охране атмосферного воздуха ранее не "
                                 "разрабатывались. [требуется: подтвердить или перечислить мероприятия]"))
    d.h("1.3. Сведения о результатах предыдущей инвентаризации", 2)
    d.p(str(c.get("previous") or
            f"Инвентаризация стационарных источников и выбросов вредных (загрязняющих) "
            f"веществ в атмосферный воздух для объекта ОНВ "
            f"{org.name or org.short_name or ''} проводится впервые. "
            f"[требуется: подтвердить; если была — дата, изменения на объекте и их причины (п. 35 «в»)]"))
    d.h("1.4. Краткая характеристика прилегающей к объекту ОНВ местности", 2)
    d.p(str(c.get("surroundings") or _req(
        "характер местности (селитебная/промышленная зона), соседние участки по сторонам "
        "света, расстояние до ближайшей жилой застройки и зон с особыми условиями "
        "(п. 35 «г» Порядка № 871)")))
    d.h("1.5. Размеры и границы санитарно-защитной зоны объекта ОНВ", 2)
    d.p(str(c.get("szz") or _req(
        "класс по СанПиН 2.2.1/2.1.1.1200-03, ориентировочный размер СЗЗ, реквизиты "
        "решения об установлении СЗЗ (п. 35 «д»)")))
    d.page_break()

    # ── Раздел 2 ────────────────────────────────────────────────────────
    d.h(f"2. {inv.SECTIONS[1][1]}")
    d.p("При проведении инвентаризации выбросов проведены следующие работы:")
    d.bullets(WORKS_DONE)
    d.typical("Перечень работ приведён по пп. 6–9 Порядка № 871.")
    d.p("При инвентаризации использовались следующие нормативно-методические документы:")
    d.bullets(INTRO_BASIS[:2] + INTRO_BASIS[3:5] + INTRO_BASIS[6:7] + INTRO_BASIS[8:])
    d.typical(CALC_METHODS_WHEN)
    methods = c.get("methods") or sorted({s["method"] for s in srcs if s["method"]})
    if methods:
        d.p("Перечень использованных методик расчётного определения выбросов:")
        d.bullets([str(m) for m in methods])
    else:
        d.p(_req("перечень методик расчёта по источникам из распоряжения № 35-р"))
    measured = [s["number"] for s in srcs if s["measured"]]
    d.p("Инвентаризация проведена "
        + ("расчётным и инструментальным методом." if measured else
           "расчётным методом. [требуется: подтвердить; если были замеры — укажите "
           "источники с measured=true и протоколы]"))
    if c.get("measurement_methods"):
        d.p("Методики выполнения измерений:")
        d.bullets([str(m) for m in c["measurement_methods"]])
    d.page_break()

    # ── Раздел 3 ────────────────────────────────────────────────────────
    d.h(f"3. {inv.SECTIONS[2][1]}")
    d.typical(MAP_REQUIREMENTS)
    d.p(str(c.get("map") and f"Карта-схема расположения ИЗАВ: {c['map']} (Приложение 11)."
            or _req("карта-схема территории объекта ОНВ с ИЗАВ, СЗЗ и жилой застройкой — "
                    "вложите файл и укажите путь в air_inventory.map (п. 37 Порядка)")))
    d.page_break()

    # ── Раздел 4 ────────────────────────────────────────────────────────
    d.h(f"4. {inv.SECTIONS[3][1]}")
    d.h("4.1. Источники выделения загрязняющих веществ", 2)
    if c.get("emitters_text"):
        d.p(str(c["emitters_text"]))
    for s in srcs:
        d.p(f"{'Организованный' if 'неорг' not in s['kind'] else 'Неорганизованный'} "
            f"источник № {s['number'] or '—'}. {s['name'] or _req('наименование')}. "
            f"В атмосферу выделяются: "
            f"{', '.join(p['name'] or p['code'] for p in s['pollutants']) or _req('вещества')}."
            + (f" Высота выброса — {s['height']} м, диаметр — {s['diameter']} м. "
               f"Скорость выхода ГВС {s['speed']} м/с, объём ГВС — {s['volume']} м³/с."
               if s["height"] and s["diameter"] and s["speed"] and s["volume"] else ""))
    if not srcs:
        d.p(_req("описание источников выделения по цехам/участкам"))
    d.table(inv.T31_HEADER, inv.rows_t31(ctx), title="Таблица № 4.1.1 (табл. 3.1 Порядка) " +
            inv.T31_TITLE.split(". ", 1)[1], font_pt=7)
    d.h("4.2. Источники выбросов загрязняющих веществ", 2)
    d.p("Все источники выбросов загрязняющих веществ для рассматриваемой промплощадки "
        "представлены в таблице 4.2.1.")
    d.table(inv.T32_HEADER, inv.rows_t32(ctx), title="Таблица № 4.2.1 (табл. 3.2 Порядка) "
            "Источники выбросов загрязняющих веществ", font_pt=6)
    d.h("4.3. Результаты обследования ГОУ и условий их эксплуатации", 2)
    d.table(inv.T36_HEADER, inv.rows_t36(ctx) or (
        [["ГОУ на объекте отсутствуют"] + [""] * 10] if c.get("has_gou") is False else []),
        title="Таблица № 4.3.1 (табл. 3.6 Порядка) Результаты обследования ГОУ и условий "
              "их эксплуатации", font_pt=7)
    d.h("4.4. Суммарные выбросы по объекту ОНВ", 2)
    rows37, tot37 = inv.rows_t37(ctx)
    d.table(inv.T37_HEADER, rows37, totals=tot37,
            title="Таблица № 4.4.1 (табл. 3.7 Порядка) Суммарные выбросы ЗВ в атмосферный "
                  "воздух (т/год), их очистка и утилизация (в целом по объекту ОНВ)", font_pt=7)
    if c.get("mobile"):
        d.table(inv.T38_HEADER, [[str(x) for x in r] for r in c["mobile"]],
                title="Таблица № 4.5.1 (табл. 3.8 Порядка) Выбросы от передвижных ИЗАВ", font_pt=7)
    d.page_break()

    # ── Раздел 5 ────────────────────────────────────────────────────────
    d.h(f"5. {inv.SECTIONS[4][1]}")
    by_method: dict[str, list[str]] = {}
    for s in srcs:
        if s["method"] and not s["measured"]:
            by_method.setdefault(str(s["method"]), []).append(s["number"])
    if by_method:
        for m, nums in by_method.items():
            d.p(f"Расчёт выбросов от источников № {', '.join(nums)} выполнен в соответствии с «{m}».")
    else:
        d.p(_req("по каждому расчётному источнику — методика из перечня № 35-р и исходные "
                 "данные (расход топлива/сырья, время работы)"))
    d.p(str(c.get("calc_text") or "Расчёты выбросов приведены в Приложении 3. Исходные "
                                  "данные по предприятию — Приложение 1."))
    d.page_break()

    # ── Раздел 6 ────────────────────────────────────────────────────────
    d.h(f"6. {inv.SECTIONS[5][1]}")
    if measured:
        d.p(f"Инструментальные измерения показателей выбросов загрязняющих веществ "
            f"выполнены для источников № {', '.join(measured)}. Протоколы измерений — "
            f"Приложение 9, аттестат аккредитации лаборатории — Приложение 10.")
    else:
        d.p("Инструментальное определение показателей выбросов не проводилось. "
            "[требуется: подтвердить]")
    d.table(inv.T21_HEADER, inv.rows_t21(ctx), title=inv.T21_TITLE, font_pt=6)
    d.page_break()

    # ── Раздел 7 ────────────────────────────────────────────────────────
    d.h(f"7. {inv.SECTIONS[6][1]}")
    ns = inv.nonstationary_rows(ctx)
    d.table(inv.T11_HEADER, ns["11"], title="Таблица 7.1 – " + inv.T11_TITLE.split(". ", 1)[1], font_pt=7)
    d.table(inv.T12_HEADER, ns["12"], title="Таблица 7.2 – " + inv.T12_TITLE.split(". ", 1)[1], font_pt=7)
    d.table(inv.T13_HEADER, ns["13"], title="Таблица 7.3 – " + inv.T13_TITLE.split(". ", 1)[1], font_pt=7)
    d.page_break()

    # ── Приложения ─────────────────────────────────────────────────────
    d.h("ПРИЛОЖЕНИЯ")
    for a in inv.APPENDICES:
        d.p(f"{a} — {_req('вложить')}")
    problems = inv.gaps(ctx)
    if problems:
        d.h("Чего не хватает для полного отчёта (служебный лист, удалить перед выдачей)", 2)
        for t in problems:
            d.p(f"– {t}")
    return d.save(out_path)
