def _req(text: str) -> str:
    return f"[требуется: {text}]"


def _val(v, need: str) -> str:
    return str(v) if v not in (None, "") else _req(need)


class _Doc:
    """Тонкая обёртка над python-docx: заголовки, абзацы, таблицы с нумерацией граф."""

    def __init__(self):
        from docx import Document
        from docx.shared import Cm, Pt
        self.doc = Document()
        st = self.doc.styles["Normal"]
        st.font.name = "Times New Roman"
        st.font.size = Pt(12)
        for s in self.doc.sections:
            s.left_margin, s.right_margin = Cm(2.5), Cm(1.5)
            s.top_margin, s.bottom_margin = Cm(2), Cm(2)

    def h(self, text: str, level: int = 1):
        p = self.doc.add_paragraph()
        r = p.add_run(text)
        r.bold = True
        from docx.shared import Pt
        r.font.size = Pt(14 if level == 1 else 12)
        return p

    def p(self, text: str = "", *, italic: bool = False, bold: bool = False, center: bool = False):
        from docx.enum.text import WD_ALIGN_PARAGRAPH as AL
        para = self.doc.add_paragraph()
        if center:
            para.alignment = AL.CENTER
        r = para.add_run(text)
        r.italic, r.bold = italic, bold
        return para

    def typical(self, text: str):
        """Типовой текст с пометкой — чтобы юзер видел, что это не его данные."""
        para = self.doc.add_paragraph()
        para.add_run(text)
        para.add_run(f" {TYPICAL}").italic = True
        return para

    def bullets(self, items: list[str]):
        for it in items:
            self.doc.add_paragraph(f"– {it}")

    def table(self, header: list[str], rows: list[list[str]], title: str | None = None,
              totals: list[list[str]] | None = None, numbered: bool = True,
              font_pt: int = 8):
        from docx.shared import Pt
        if title:
            self.p(title, bold=True)
        t = self.doc.add_table(rows=1, cols=len(header))
        t.style = "Table Grid"
        for i, text in enumerate(header):
            t.rows[0].cells[i].text = text
        if numbered:  # строка номеров граф «1 2 … n» — как в бланках № 871
            cells = t.add_row().cells
            for i in range(len(header)):
                cells[i].text = str(i + 1)
        body = rows or [[_req("данные не заведены")] + [""] * (len(header) - 1)]
        for r in list(body) + list(totals or []):
            cells = t.add_row().cells
            for i, text in enumerate(r[:len(header)]):
                cells[i].text = str(text)
        for row in t.rows:
            for c in row.cells:
                for para in c.paragraphs:
                    for run in para.runs:
                        run.font.size = Pt(font_pt)
        self.doc.add_paragraph()
        return t

    def kv_table(self, pairs: list[tuple[str, str]]):
        t = self.doc.add_table(rows=0, cols=2)
        t.style = "Table Grid"
        for k, v in pairs:
            cells = t.add_row().cells
            cells[0].text, cells[1].text = k, v
        self.doc.add_paragraph()

    def page_break(self):
        self.doc.add_page_break()

    def save(self, path: Path) -> Path:
        path.parent.mkdir(parents=True, exist_ok=True)
        self.doc.save(path)
        return path


