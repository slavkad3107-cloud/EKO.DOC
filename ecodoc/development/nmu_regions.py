def region_code(ctx: ReportContext) -> str:
    """Код субъекта РФ первого объекта: region_code, иначе из кода ОНВОС."""
    if not ctx.objects:
        return ""
    obj = ctx.objects[0]
    from ecodoc.core.nvos import subject_code
    # region_code в базе — префикс ОКТМО из кода ОНВОС (40 = СПб), а профили
    # ждут код субъекта (78): переводим единой функцией ядра
    code = subject_code(obj.region_code) or subject_code(obj.code)
    if code:
        return code
    m = re.match(r"\s*\d{2}-(\d{4})-", str(obj.code or ""))
    # запасной путь: вторая группа — «01» + код субъекта («0177»)
    return m.group(1)[-2:] if m else ""


def profile(ctx: ReportContext) -> dict | None:
    """Региональный профиль или None (федеральный образец № 662)."""
    return REGIONS.get(region_code(ctx))


def effect_pct(before: str, after: str) -> str:
    """Графа «эффект, %» СПб: целое число, как в принятом перечне
    (43, 7, 20); при непосчитанном «после» — пометка, не выдумываем."""
    from decimal import Decimal, ROUND_HALF_UP
    try:
        b = Decimal(before.replace(",", "."))
        a = Decimal(after.replace(",", "."))
    except Exception:
        return EFFECT_REQUIRED
    if b <= 0:
        return "0"
    pct = (b - a) / b * 100
    return str(int(pct.quantize(Decimal("1"), rounding=ROUND_HALF_UP)))
