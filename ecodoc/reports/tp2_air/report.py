@register
class TP2Air(Report):
    code = "2tp-air"
    title = "2-ТП (воздух)"

    def _extra(self) -> dict:
        return self.ctx.extra.get("tp2_air", {}) if isinstance(self.ctx.extra, dict) else {}

    def _air(self):
        """Вещества воздуха БЕЗ групп суммации.

        Коды 6xxx — это группы суммации («азота диоксид + серы диоксид»), а не
        отдельные вещества: их массы уже учтены в составляющих, и включение
        группы в отчёт даёт двойной счёт."""
        from ecodoc.core import sanitize
        return [p for p in self.ctx.pollutants
                if p.medium == Medium.AIR and not sanitize.is_sum_group(p.code)]

    def _sum_groups(self):
        from ecodoc.core import sanitize
        return [p for p in self.ctx.pollutants
                if p.medium == Medium.AIR and sanitize.is_sum_group(p.code)]

    # ---- ОНВ: коды для шапки каждого раздела -------------------------------
    def _onv(self) -> dict:
        """Код ОНВ / ОКТМО ОНВ / ОКВЭД2 ОНВ для шапок разделов.

        Форма подаётся по объекту (п. 14, 17 Указаний): коды берём из первого
        объекта базы. ОКТМО ОНВ — тот, что указан при постановке на учёт, у
        организации это другой реквизит (место платы), поэтому подстановки
        нет — пусто + предупреждение. ОКВЭД2 по п. 17 — «код основного вида
        экономической деятельности», т.е. реквизит респондента: без своего у
        объекта берём ОКВЭД организации."""
        objs = self.ctx.objects or []
        obj = objs[0] if objs else None
        o = self.ctx.organization
        return {
            "code": (getattr(obj, "code", "") or "") if obj else "",
            "oktmo": (getattr(obj, "oktmo", "") or "") if obj else "",
            "okved": ((getattr(obj, "okved", "") or "") if obj else "") or (o.okved or ""),
        }

    def validate(self) -> list[Issue]:
        issues: list[Issue] = []
        o = self.ctx.organization
        if not o.inn:
            issues.append(Issue("error", "ИНН", "не указан ИНН"))
        if not o.okpo:
            issues.append(Issue("warning", "ОКПО", "для 2-ТП обязателен код ОКПО"))
        if not o.address:
            issues.append(Issue("warning", "адрес", "в титуле бланка есть строка "
                                "«Почтовый адрес» — адрес организации не указан"))
        if not self.ctx.period.year:
            issues.append(Issue("error", "период", "не указан отчётный год"))
        if not self._air():
            issues.append(Issue("error", "выбросы", "нет веществ с выбросами в воздух"))
        # ОНВ — по п. 14 Указаний обязателен в каждом разделе
        onv = self._onv()
        objs = self.ctx.objects or []
        if not onv["code"]:
            issues.append(Issue(
                "warning", "ОНВ",
                "не указан код ОНВ — в шапке каждого раздела бланка поле «Код ОНВ» "
                "останется пустым (форма подаётся по каждому объекту)"))
        if objs and not onv["oktmo"]:
            issues.append(Issue(
                "warning", "ОНВ",
                "у объекта ОНВ не указан ОКТМО — поле «Код ОКТМО ОНВ» Раздела 1 "
                "останется пустым (подставлять ОКТМО организации нельзя: это код "
                "места внесения платы)"))
        if len(objs) > 1:
            issues.append(Issue(
                "warning", "ОНВ",
                f"в базе {len(objs)} объектов ОНВ, а форма подаётся отдельно по "
                f"каждому (п. 17 Указаний); все выбросы отнесены к первому — "
                f"{objs[0].code or objs[0].name}; для остальных сформируйте "
                "отдельные базы"))
        groups = self._sum_groups()
        if groups:
            names = ", ".join(f"{p.code} {p.name}"[:40] for p in groups[:3])
            issues.append(Issue(
                "warning", "выбросы",
                f"из отчёта исключены группы суммации ({len(groups)}): {names}"
                f"{' …' if len(groups) > 3 else ''} — их массы уже учтены в "
                f"веществах, входящих в группу"))
        sec = self._section1()
        # Гр.3 бланка («в т.ч. от организованных») в модели данных источника
        # не имеет — без ввода печатается прочерк; молчать об этом нельзя,
        # иначе пользователь узнает о пустой графе от инспектора.
        if self._air() and all(sec[n]["g7"] is None for n in _SECT1_DETAIL):
            issues.append(Issue(
                "warning", "раздел 1",
                "не заполнена графа 3 «в том числе от организованных источников "
                "загрязнения» — в форме будет прочерк; укажите тоннаж в "
                "extra['tp2_air']['cleaning'][<строка>]['g7']"))
        bad_org = [n for n in _SECT1_DETAIL
                   if sec[n]["g7"] is not None and sec[n]["g7"] > sec[n]["g2"]]
        if bad_org:
            issues.append(Issue(
                "error", "раздел 1",
                f"графа 3 больше графы 2 в строках {', '.join(map(str, bad_org))}"
                " — выброс от организованных источников не может превышать весь"
                " выброс без очистки"))
        # Контрольное соотношение 1 Указаний: гр.7 = гр.2 + (гр.4 − гр.5)
        # (внутренние ключи: g6 = g3 − g4 + g2).
        bad_ctl = [n for n in _SECT1_DETAIL
                   if sec[n]["g6"] != sec[n]["g3"] - sec[n]["g4"] + sec[n]["g2"]]
        if bad_ctl:
            issues.append(Issue(
                "warning", "раздел 1",
                "нарушено контрольное соотношение Указаний гр.7 = гр.4 − гр.5 "
                f"+ гр.2 в строках {', '.join(map(str, bad_ctl))} — проверьте "
                "данные очистки в extra['tp2_air']['cleaning']"))
        # Раздел 2: вещества вне Перечня ушли в 8888 — пользователь должен
        # знать, что именно свёрнуто (в форме их названий уже не будет)
        other = [p for p in self._sect2_other()]
        if other:
            names = ", ".join(f"{_code(p.code)} {p.name}"[:40] for p in other[:3])
            issues.append(Issue(
                "warning", "раздел 2",
                f"вещества вне Перечня приложения к № 661 ({len(other)}) свёрнуты "
                f"в строку 8888 «{_OTHER_NAME}»: {names}"
                f"{' …' if len(other) > 3 else ''}"))
        # Раздел 3: строки 302/303 без ввода пустые — программа не выдумывает
        src = self._extra().get("sources") or {}
        if src and not (src.get("pdv") or src.get("vsv")):
            issues.append(Issue(
                "warning", "раздел 3",
                "строки 302/303 (источники с нормативами ПДВ/ВСВ) не заполнены — "
                "укажите extra['tp2_air']['sources']['pdv'|'vsv'] = "
                "{total, organized, allowed, fact}"))
        if not src:
            issues.append(Issue(
                "warning", "раздел 3",
                "нет данных об источниках (extra['tp2_air']['sources']) — в "
                "Разделе 3 будут прочерки по количеству источников и "
                "разрешённому выбросу"))
        if len(self._extra().get("measures") or []) > 5:
            issues.append(Issue(
                "warning", "раздел 4",
                "в бланке Раздела 4 пять строк (401-405) — в форму попадут "
                "только первые пять мероприятий"))
