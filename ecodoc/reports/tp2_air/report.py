    def _sect2_candidates(self):
        """Вещества, подлежащие отражению в Разделе 2: все, кроме SO2/CO/NOx
        (строки 104-106 Раздела 1 — сноска <2> к Разделу 2 бланка).

        Исключаем по строке Раздела 1, а не по коду: так отсекаются и старые
        коды (3003/3332/3004) и «именные» SO2/CO/NOx. Но вещество из Перечня
        (например, 0333 сероводород, который в Разделе 1 идёт в сернистые)
        остаётся — Перечень требует его показать отдельно."""
        return [p for p in self._air()
                if _air_row(p) not in _SECT2_EXCLUDED_ROWS
                or _code(p.code) in SECT2_SPECIFIC]

    def _sect2_other(self):
        return [p for p in self._sect2_candidates()
                if _code(p.code) not in SECT2_SPECIFIC]

    def _section2(self) -> list[tuple[int, str, str, Decimal]]:
        """Строки Раздела 2: (№ строки, код ЗВ, наименование, выброс).

        Вещества Перечня — каждое своей строкой (одинаковые коды суммируются,
        название — по Перечню, как в бланке); остальные — одна строка 8888
        суммарно (п. 19 Указаний). Нумерация 201, 202… по порядку."""
        by_code: dict[str, Decimal] = {}
        for p in self._sect2_candidates():
            c = _code(p.code)
            if c in SECT2_SPECIFIC:
                by_code[c] = by_code.get(c, Decimal("0")) + _tot(p)
        rows = []
        for i, c in enumerate(sorted(by_code), 201):
            rows.append((i, c, SECT2_SPECIFIC[c], by_code[c]))
        other = self._sect2_other()
        if other:
            rows.append((201 + len(rows), _OTHER_CODE, _OTHER_NAME,
                         sum((_tot(p) for p in other), Decimal("0"))))
        return rows

    # ---- Раздел 3: строки 301-303 ------------------------------------------
    def _section3(self) -> list[tuple[int, str, dict]]:
        """Строки 301-303: (№, графа Б, {total, organized, allowed, fact}).

        301 — из sources верхнего уровня (fact по умолчанию = сумма гр.7);
        302/303 — из sources['pdv'] / sources['vsv']; без ввода — прочерки,
        ничего не выдумываем (по п. 20 Указаний их заполняют только имеющие
        разрешение на выброс)."""
        src = self._extra().get("sources") or {}
        total = sum((_tot(p) for p in self._air()), Decimal("0"))
        out = []
        for row, label, key in _SECT3_ROWS:
            d = src if key is None else (src.get(key) or {})
            vals = {k: d.get(k, "-") for k in ("total", "organized", "allowed", "fact")}
            if key is None and "fact" not in src:
                vals["fact"] = total
            out.append((row, label, vals))
        return out

