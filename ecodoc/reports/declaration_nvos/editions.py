@dataclass(frozen=True)
class Edition:
    key: str
    npa: str                      # реквизиты приказа для заголовков листов
    header: str                   # шапка «Приложение 2 к приказу …»
    kinds: tuple                  # виды платы в порядке строк 021–02N
    # блоки «КБК / ОКТМО / сумма / подстроки» для видов платы, у которых они
    # есть в итоговой части: kind → (код КБК, код ОКТМО, код суммы, подстроки)
    blocks: dict = field(default_factory=dict)
    # «старые» пять видов (выбросы/ПНГ/сбросы/отходы/ТКО) — только у них есть
    # строки зачёта 181–185, авансов 191–195 и возврата 211–215
    five: tuple = ("air", "png", "water", "waste", "tko")
    section4_has_kp: bool = True  # графа «Кп» (взвешенные вещества) в Разделе 4
    section5_kpo_name: str = "Кпо"  # в № 182 стимулирующий коэффициент назван «Кло»
    has_section10: bool = False
    title_has_msp: bool = False   # поле «Относится к субъектам МСП» на титуле

    def kind_index(self, kind: str) -> int:
        """Порядковый номер вида платы (1..N) — последняя цифра кодов
        151–159, 161–169, 171–179, 201–209."""
        return self.kinds.index(kind) + 1


