def edition_for_year(year) -> Edition:
    """Редакция формы по отчётному году.

    Декларация подаётся до 10 марта следующего года, поэтому за 2025 год она
    сдаётся по ред. № 241 (действует с 01.09.2025), а за 2026 и далее — по
    № 182 (с 01.09.2026). Без года печатаем действующую на сегодня форму
    № 182 — она же останется верной для всех будущих периодов."""
    try:
        y = int(year or 0)
    except (TypeError, ValueError):
        y = 0
    if 0 < y <= 2025:
        return EDITIONS["241"]
    return EDITIONS["182"]


