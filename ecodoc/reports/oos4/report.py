"""Форма № 4-ОС «Сведения о текущих затратах на охрану окружающей среды».

Статистическая форма Росстата (ОКУД 0609030, приказ Росстата от 22.07.2025
№ 346, приложение № 2): годовая, сдаётся с 1-го рабочего дня по 25 января
после отчётного периода в территориальный орган Росстата. Данные здесь
**денежные** — программа берёт их из `ctx.extra['oos4']['costs']`, куда их
вносит эколог по данным бухгалтерии (вкладка «Отчётность» → «Общая»).

Структура действующего бланка (ред. 22.07.2025, вводится с отчёта за 2025
год): одна таблица «Выполнение работ по охране окружающей среды», строки
01…10 (01 — «Охрана окружающей среды - всего», контрольная сумма строк
02–10), первые графы А/Б, затем два блока по 8 граф: «Для собственных нужд
(кроме предоставления специализированных природоохранных услуг)» (гр. 3–10)
и «Специализированные природоохранные услуги» (гр. 11–18).

Программа заполняет графы «всего» (гр. 3 и 11); расшифровочные графы
(за счёт собственных средств, материальные затраты, оплата труда, оплата
услуг, капремонт, выручка от побочной продукции, амортизация) остаются
пустыми — их эколог заполняет вручную, если ведёт такой учёт.

Платы за НВОС в действующей форме НЕТ: раздел о плате исключён, когда форма
была переименована из «4-ОС (затраты)» в нынешнюю редакцию. Поэтому здесь
плата не считается и не печатается — она в декларации.
"""
from __future__ import annotations

from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

from ecodoc.core.models import Issue
from ecodoc.core.registry import register
from ecodoc.render import xlsx
from ecodoc.reports.base import Report

# Показатели формы: (код строки, наименование по бланку, ключ в
# extra.oos4.costs). Строка 01 «Охрана окружающей среды - всего» — сумма
# строк 02–10, отдельного ключа не имеет. Порядок и формулировки — дословно
# из приложения № 2 к приказу Росстата от 22.07.2025 № 346.
LINES = [
    ("02", "охрана атмосферного воздуха и предотвращение изменения климата",
     "air"),
    ("03", "обращение со сточными водами", "water"),
    ("04", "обращение с отходами", "waste"),
    ("05", "защита и экологическая реабилитация земель, поверхностных "
           "и подземных водных объектов", "land"),
    ("06", "снижение шумового и вибрационного воздействия", "noise"),
    ("07", "сохранение биоразнообразия и охрана природных территорий", "bio"),
    ("08", "радиационная безопасность окружающей среды (за исключением мер "
           "по предотвращению аварий и катастроф)", "radiation"),
    ("09", "научно-исследовательская деятельность и разработки в области "
           "охраны окружающей среды", "science"),
    ("10", "другие направления деятельности в области охраны окружающей "
           "среды", "other"),
]

# Графы бланка: два блока по 8 граф. Заголовки — дословно из бланка;
# групповые подзаголовки («Текущие (эксплуатационные) затраты за год:»,
# «Из гр. N состав текущих затрат по основным видам:») включены в текст
# графы. Программа заполняет графы «всего» (гр. 3 и 11), остальные пустые.
COLS_OWN = [
    ("3", "Текущие (эксплуатационные) затраты за год: всего"),
    ("4", "Текущие (эксплуатационные) затраты за год: из них за счет "
          "собственных средств"),
    ("5", "Из гр. 3 состав текущих затрат по основным видам: материальные "
          "затраты"),
    ("6", "Из гр. 3 состав текущих затрат по основным видам: затраты на "
          "оплату труда и отчисления на социальные нужды"),
    ("7", "Оплата услуг природоохранного назначения"),
    ("8", "Затраты на капитальный ремонт основных фондов по охране "
          "окружающей среды"),
    ("9", "Выручка (поступления) от продажи побочной продукции"),
    ("10", "Амортизационные отчисления на восстановление основных фондов "
           "по охране окружающей среды"),
]
COLS_SERVICES = [
    ("11", "Текущие (эксплуатационные) затраты за год: всего"),
    ("12", "Текущие (эксплуатационные) затраты за год: из них за счет "
           "собственных средств"),
    ("13", "Из гр. 11 состав текущих затрат по основным видам: материальные "
           "затраты"),
    ("14", "Из гр. 11 состав текущих затрат по основным видам: затраты на "
           "оплату труда и отчисления на социальные нужды"),
    ("15", "Оплата услуг природоохранного назначения"),
    ("16", "Затраты на капитальный ремонт основных фондов по охране "
           "окружающей среды"),
    ("17", "Выручка (поступления) от продажи побочной продукции"),
    ("18", "Амортизационные отчисления на восстановление основных фондов "
           "по охране окружающей среды"),
]


def _dec(value) -> Decimal:
    try:
        return Decimal(str(value).replace(",", ".").replace(" ", ""))
    except Exception:
        return Decimal("0")


def _whole(value: Decimal) -> int:
    """Тысячи рублей в целых числах — п. 10 Указаний по заполнению (№ 346)."""
    return int(value.quantize(Decimal("1"), rounding=ROUND_HALF_UP))


@register
class OOS4(Report):
    code = "4-oos"
    title = "4-ОС — сведения о текущих затратах на охрану окружающей среды"
    domain = "reporting"
    has_xml = False          # сдаётся через систему сбора Росстата (ЭВФ)

    # ── данные ────────────────────────────────────────────────────────
    @property
    def data(self) -> dict:
        return (self.ctx.extra or {}).get("oos4", {}) or {}

    def costs(self) -> list[tuple]:
        """(код строки, наименование, сумма) по направлениям затрат."""
        src = self.data.get("costs", {}) or {}
        return [(code, name, _dec(src.get(key))) for code, name, key in LINES]

    def total(self) -> Decimal:
        """Строка 01 — контрольная сумма строк 02–10."""
        return sum((v for _c, _n, v in self.costs()), Decimal("0"))

    def services(self) -> dict:
        """Затраты по специализированным природоохранным услугам (гр. 11)."""
        return self.data.get("services", {}) or {}

    # ── проверки ──────────────────────────────────────────────────────
    def validate(self) -> list[Issue]:
        issues: list[Issue] = []
        org = self.ctx.organization
        if not org.inn:
            issues.append(Issue("error", "ИНН", "не указан ИНН"))
        if not org.okpo:
            issues.append(Issue("warning", "ОКПО",
                                "для статистической формы нужен код ОКПО"))
        if not self.ctx.period.year:
            issues.append(Issue("error", "period.year", "не указан отчётный год"))
        if not self.total():
            issues.append(Issue(
                "warning", "затраты на ООС",
                "не заданы текущие затраты на охрану окружающей среды — "
                "заполните их во вкладке «Отчётность» → модуль «Общая» → "
                "«Программа ПЭК и затраты на ООС»"))
        return issues

    def render_xml(self, out_path: Path) -> Path:
        # 4-ОС сдаётся через систему сбора Росстата (электронная версия формы),
        # отдельного XML-конверта у неё нет — печатная форма и есть результат
        raise NotImplementedError(
            "4-ОС не выгружается в XML: форма сдаётся через систему сбора "
            "отчётности Росстата (websbor), используйте печатную форму")

    # ── печать ────────────────────────────────────────────────────────
    def render_print(self, out_path: Path) -> Path:
        out_path = self._ensure_dir(out_path)
        org, per = self.ctx.organization, self.ctx.period
        wb = xlsx.new_workbook()

        ws = wb.create_sheet("Титул")
        xlsx.merge(ws, "A1:E1", "Форма № 4-ОС", bold=True, align="center")
        xlsx.merge(ws, "A2:E2", "Сведения о текущих затратах на охрану "
                                "окружающей среды", align="center")
        xlsx.merge(ws, "A3:E3", f"за {per.year or '____'} год", align="center")
        xlsx.merge(ws, "A4:E4", "Код формы по ОКУД 0609030 · годовая · "
                                "предоставляется с 1-го рабочего дня по "
                                "25 января после отчетного периода "
                                "в территориальный орган Росстата",
                   align="center")
        xlsx.merge(ws, "A5:E5", "Утверждена приказом Росстата от 22.07.2025 "
                                "№ 346", align="center")
        info = [("Наименование отчитывающейся организации",
                 org.name or org.short_name),
                ("Почтовый адрес", org.address),
                ("ИНН", org.inn), ("ОКПО", org.okpo), ("ОКТМО", org.oktmo),
                ("ОКВЭД2", org.okved),
                ("Должностное лицо", org.director_name),
                ("Телефон / e-mail", f"{org.phone or '—'} / {org.email or '—'}")]
        for i, (label, value) in enumerate(info, start=7):
            xlsx.cell(ws, f"A{i}", label, bold=True)
            xlsx.merge(ws, f"B{i}:E{i}", value or "—", align="left")
        xlsx.widths(ws, {"A": 44, "B": 26, "C": 18, "D": 18, "E": 18})

        # ── единая таблица бланка ────────────────────────────────────
        ws1 = wb.create_sheet("Форма")
        ncols = 2 + len(COLS_OWN) + len(COLS_SERVICES)

        def L(n: int) -> str:                        # 1→A, 2→B, …
            return chr(ord("A") + n - 1)

        xlsx.merge(ws1, f"A1:{L(ncols)}1",
                   "Выполнение работ по охране окружающей среды, "
                   "тысяча рублей", bold=True, align="left")
        # двухуровневая шапка: над графами — названия блоков бланка
        own_from, own_to = 3, 2 + len(COLS_OWN)
        svc_from, svc_to = own_to + 1, own_to + len(COLS_SERVICES)
        xlsx.merge(ws1, f"{L(own_from)}2:{L(own_to)}2",
                   "Для собственных нужд (кроме предоставления "
                   "специализированных природоохранных услуг)", bold=True)
        xlsx.merge(ws1, f"{L(svc_from)}2:{L(svc_to)}2",
                   "Специализированные природоохранные услуги", bold=True)
        headers = ["Наименование направлений природоохранной деятельности",
                   "N строки"] \
            + [n for _c, n in COLS_OWN] + [n for _c, n in COLS_SERVICES]
        xlsx.header_row(ws1, 3, headers)
        # строка нумерации граф — как в бланке: А, Б, 3–10, 11–18
        xlsx.data_row(ws1, 4, ["А", "Б"] + [c for c, _n in COLS_OWN]
                      + [c for c, _n in COLS_SERVICES])

        svc = self.services()
        blanks_own = [None] * (len(COLS_OWN) - 1)
        blanks_svc = [None] * (len(COLS_SERVICES) - 1)
        # строка 01 — всего (контрольная сумма строк 02–10)
        xlsx.data_row(ws1, 5, ["Охрана окружающей среды - всего",
                               "01", float(self.total()) or None, *blanks_own,
                               float(_dec(svc.get("total"))) or None, *blanks_svc])
        row = 6
        for code, name, value in self.costs():
            xlsx.data_row(ws1, row, [f"в том числе: {name}", code,
                                     float(value) or None, *blanks_own,
                                     float(_dec(svc.get(code))) or None, *blanks_svc])
            row += 1
        widths = {"A": 55, "B": 9}
        for i in range(3, ncols + 1):
            widths[L(i)] = 15
        xlsx.widths(ws1, widths)
        row += 1
        xlsx.cell(ws1, f"A{row}", "Строка 01 = сумма строк 02–10 (контрольное "
                  "соотношение бланка)", border=False, align="left")
        row += 2
        xlsx.cell(ws1, f"A{row}", f"{org.director_position or 'Руководитель'}"
                  f"  ______________  {org.director_name or ''}",
                  border=False, align="left")
        xlsx.cell(ws1, f"A{row + 2}", "«____» __________ 20___ г.",
                  border=False, align="left")
        return xlsx.save(wb, out_path)
