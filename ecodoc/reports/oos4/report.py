def _dec(value) -> Decimal:
    if value is None:
        return Decimal("0")
    try:
        return Decimal(str(value).replace(",", ".").replace(" ", ""))
    except Exception:
        return Decimal("0")


def _whole(value: Decimal) -> int:
    """Целые тысячи рублей — формат N(18,0) всех ячеек XML-шаблона 4-ОС."""
    return int(value.quantize(Decimal("1"), rounding=ROUND_HALF_UP))


def _okved_hits(okved: str, prefixes: tuple[str, ...]) -> bool:
    """Код ОКВЭД 2 респондента попадает в перечень (с подкодами:
    38.21.1 → 38.21.11…38.21.19, 03.21 → 03.21.1…03.21.9)."""
    code = (okved or "").strip()
    return bool(code) and any(code.startswith(p) for p in prefixes)


@register
class OOS4(Report):
    code = "4-oos"
    title = "4-ОС — сведения о текущих затратах на охрану окружающей среды"
    domain = "reporting"
    has_xml = False          # сдаётся через систему сбора Росстата (ЭВФ)

    # ── данные ────────────────────────────────────────────────────────
    @property
    def data(self) -> dict:
        return (self.ctx.extra or {}).get("oos4", {}) or {}

    @staticmethod
    def _pick(src: dict, code: str, key: str) -> Decimal:
        """Значение строки: по ключу («air») или по коду строки («02»)."""
        if key in src:
            return _dec(src.get(key))
        return _dec(src.get(code))

    def costs(self) -> list[tuple]:
        """(код строки, наименование, сумма гр. 3) по направлениям затрат."""
        src = self.data.get("costs", {}) or {}
        return [(code, name, self._pick(src, code, key))
                for code, name, key in LINES]

    def total(self) -> Decimal:
        """Строка 01 гр. 3 — контрольная сумма строк 02–10."""
        return sum((v for _c, _n, v in self.costs()), Decimal("0"))

    def services(self) -> list[tuple]:
        """(код строки, наименование, сумма гр. 11) — специализированные
        природоохранные услуги (блок граф 11–18)."""
        src = self.data.get("services", {}) or {}
        return [(code, name, self._pick(src, code, key))
                for code, name, key in LINES]

    def services_total(self) -> Decimal:
        """Строка 01 гр. 11 — сумма строк 02–10 (контроль 1 бланка)."""
        return sum((v for _c, _n, v in self.services()), Decimal("0"))

    def paid_services(self) -> Decimal:
        """Оплата услуг природоохранного назначения по стр. 01 (гр. 7 / 15),
        если эколог ведёт её отдельно — для порога 100 тыс. руб. (п. 4)."""
        return _dec(self.data.get("paid_services"))

    # ── проверки ──────────────────────────────────────────────────────
    def validate(self) -> list[Issue]:
        issues: list[Issue] = []
        org = self.ctx.organization
        if not org.okpo:
            issues.append(Issue(
                "warning", "ОКПО",
                "в кодовой части бланка нужен код ОКПО (для обособленного "
                "и головного подразделения — идентификационный номер, "
                "п. 3 Указаний)"))
        if not self.ctx.period.year:
            issues.append(Issue("error", "period.year", "не указан отчётный год"))
        total, svc_total = self.total(), self.services_total()
        if not total and not svc_total:
            issues.append(Issue(
                "warning", "затраты на ООС",
                "не заданы текущие затраты на охрану окружающей среды — "
                "заполните их во вкладке «Отчётность» → модуль «Общая» → "
                "«Программа ПЭК и затраты на ООС»"))
        elif (total <= THRESHOLD_THOUSANDS and svc_total <= THRESHOLD_THOUSANDS
              and self.paid_services() <= THRESHOLD_THOUSANDS):
            issues.append(Issue(
                "warning", "порог 100 тыс. руб.",
                "по п. 4 Указаний (ред. приказа Росстата от 10.10.2025 № 566) "
                "форму предоставляют при текущих затратах на ООС и (или) оплате "
                "услуг природоохранного назначения более 100 тысяч рублей в "
                "год (виды затрат не суммируются); контроль 11 бланка: "
                "гр. 3 или 7 или 11 или 15 по стр. 01 ≥ 100 — при меньших "
                "суммах отчёт не сдаётся (п. 7: нет явления — нет отчёта)"))
        src_svc = self.data.get("services", {}) or {}
        if "total" in src_svc and _dec(src_svc.get("total")) != svc_total:
            issues.append(Issue(
                "warning", "услуги: строка 01",
                "итог по специализированным услугам (гр. 11) берётся как сумма "
                "строк 02–10 (контроль 1 бланка), заданный «total» "
                f"{src_svc.get('total')} не совпадает с суммой {svc_total}"))
        # приказ № 734: по строкам 04 и 07 не учитываются затраты по ОКВЭД
        by_code = {c: v for c, _n, v in self.costs()}
        by_code_svc = {c: v for c, _n, v in self.services()}
        for line, prefixes in OKVED_EXCLUDED.items():
            if (by_code.get(line) or by_code_svc.get(line)) and \
                    _okved_hits(org.okved, prefixes):
                issues.append(Issue(
                    "warning", f"строка {line}",
                    f"ОКВЭД {org.okved}: по строке {line} не учитываются "
                    "текущие затраты (оплата услуг природоохранного назначения) "
                    "и выручка от продажи побочной продукции по кодам "
                    f"{', '.join(prefixes)} ОКВЭД 2 (п. 12 Указаний в ред. "
                    "приказа Росстата от 19.12.2025 № 734) — проверьте, что "
                    "это затраты на собственную природоохранную деятельность, "
                    "а не основное производство"))
        return issues

