        blanks_svc = [None] * (len(COLS_SERVICES) - 1)
        # целые тысячи рублей (N(18,0) в XML-шаблоне); строка 01 — сумма
        # уже округлённых строк, чтобы контроль 1 сходился точно
        own = [(c, n, _whole(v)) for c, n, v in self.costs()]
        svc = [(c, n, _whole(v)) for c, n, v in self.services()]
        own_total = sum(v for _c, _n, v in own)
        svc_total = sum(v for _c, _n, v in svc)
        xlsx.data_row(ws1, 5, [LINE_TOTAL_NAME, "01", own_total or None,
                               *blanks_own, svc_total or None, *blanks_svc])
        xlsx.data_row(ws1, 6, ["в том числе:"] + [None] * (ncols - 1))
        row = 7
        for (code, name, value), (_c, _n, svalue) in zip(own, svc):
            xlsx.data_row(ws1, row, [name, code, value or None, *blanks_own,
                                     svalue or None, *blanks_svc])
            row += 1
        widths = {"A": 55, "B": 9}
        for i in range(3, ncols + 1):
            widths[L(i)] = 15
        xlsx.widths(ws1, widths)

        # ── подпись — блок бланка ────────────────────────────────────
        row += 1
        xlsx.merge(ws1, f"A{row}:D{row}",
                   "Должностное лицо, ответственное за предоставление "
                   "первичных статистических данных (лицо, уполномоченное "
                   "предоставлять первичные статистические данные от имени "
                   "юридического лица или от имени физического лица, "
                   "осуществляющего предпринимательскую деятельность без "
                   "образования юридического лица)", border=False, align="left")
        row += 1
        xlsx.data_row(ws1, row, [org.director_position or "",
                                 org.director_name or "", "", ""])
        row += 1
        xlsx.data_row(ws1, row, ["(должность)", "(Ф.И.О.)", "(подпись)", ""])
        row += 1
        xlsx.data_row(ws1, row, [org.phone or "", org.email or "",
                                 "«____» _________ 20__ год", ""])
        row += 1
        xlsx.data_row(ws1, row, ["(номер контактного телефона)", "(E-mail)",
                                 "(дата составления документа)", ""])

        # ── контроль при заполнении (для эколога) ─────────────────────
        row += 2
        xlsx.cell(ws1, f"A{row}", "Контроль при заполнении первичных "
                  "статистических показателей (по бланку):", bold=True,
                  border=False, align="left")
        for line in CONTROLS:
            row += 1
            xlsx.cell(ws1, f"A{row}", line, border=False, align="left")
        row += 1
        xlsx.cell(ws1, f"A{row}", "Порог респондента (п. 4 Указаний, ред. "
                  "приказа № 566): текущие затраты и (или) оплата услуг "
                  "природоохранного назначения более 100 тыс. руб. в год, "
                  "виды затрат не суммируются. Данные без НДС (п. 10).",
                  border=False, align="left")
        return xlsx.save(wb, out_path)
