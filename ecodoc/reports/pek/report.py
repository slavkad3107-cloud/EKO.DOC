def _ratio(fact, norm):
    """Гр. 9 таблицы 2.2 — превышение в раз = гр. 8 / гр. 7; без обоих
    чисел графа пустая, а не выдуманный «0»."""
    try:
        f, n = D(fact), D(norm)
    except Exception:
        return ""
    if not n or fact in ("", None):
        return ""
    return float(round(f / n, 3))


