def _split_lab(text: str) -> dict:
    """Старый одностроковый ключ pek.lab → графы таблицы 1.3: аттестат
    аккредитации (RA.RU.… / РОСС RU.…) отделяется от наименования; адрес в
    строке не хранится — прочерк."""
    import re
    text = str(text or "").strip()
    m = re.search(r"\(?\s*((?:RA\.RU|РОСС\s*RU)[^)]*)\)?\s*$", text, re.I)
    if m:
        return {"name": text[:m.start()].strip(" ,;(") or "-",
                "address": "-", "certificate": m.group(1).strip()}
    return {"name": text, "address": "-", "certificate": "-"}


def _num_row(ws, r: int, n: int) -> None:
    """Строка нумерации граф «1 | 2 | …» — обязательный элемент всех таблиц
    бланка (стоит под шапкой в каждой таблице принятых отчётов)."""
    for col in range(1, n + 1):
        c = ws.cell(row=r, column=col, value=col)
        c.border = xlsx.BORDER
        c.alignment = xlsx.CENTER


def _leaves(spec) -> int:
    return sum(_leaves(x[1]) if isinstance(x, tuple) else 1 for x in spec)


def _depth(spec) -> int:
    return max((1 + _depth(x[1]) if isinstance(x, tuple) else 1)
               for x in spec) if spec else 1


def _header(ws, r: int, spec: list, depth: int | None = None,
            col: int = 1) -> int:
    """Многоярусная шапка по спецификации (строка — графа на всю высоту,
    (текст, [подграфы]) — группа). Возвращает номер строки под шапкой."""
    depth = depth or _depth(spec)
    for item in spec:
        if isinstance(item, tuple):
            text, children = item
            width = _leaves(children)
            rng = f"{get_column_letter(col)}{r}:" \
                  f"{get_column_letter(col + width - 1)}{r}"
            if width > 1:
                xlsx.merge(ws, rng, text, bold=True, fill=True)
            else:
                xlsx.cell(ws, f"{get_column_letter(col)}{r}", text, bold=True,
                          fill=True)
            _header(ws, r + 1, children, depth - 1, col)
            col += width
        else:
            c = get_column_letter(col)
            if depth > 1:
                xlsx.merge(ws, f"{c}{r}:{c}{r + depth - 1}", item, bold=True,
                           fill=True)
            else:
                xlsx.cell(ws, f"{c}{r}", item, bold=True, fill=True)
            col += 1
    return r + depth


def flat_headers(spec) -> list[str]:
    """Плоский список граф (нижний ярус) — для проверок состава граф."""
    out: list[str] = []
    for x in spec:
        out.extend(flat_headers(x[1]) if isinstance(x, tuple) else [x])
    return out


def _table(ws, r: int, title: str, headers: list, items, keys: list[str],
           numbered: bool = True) -> int:
    """Типовая таблица бланка: заголовок, шапка (в т.ч. многоярусная),
    строка нумерации граф, данные.

    Незаполненная таблица печатается с шапкой и строкой прочерков — в
    принятых отчётах пустые таблицы формы физически присутствуют, а не
    пропускаются. Возвращает номер первой свободной строки."""
    ncols = _leaves(headers)
    xlsx.merge(ws, f"A{r}:{get_column_letter(ncols)}{r}", title, bold=True,
               border=False)
    r = _header(ws, r + 1, headers)
    _num_row(ws, r, ncols)
    r += 1
    rows = [it for it in (items or []) if isinstance(it, dict)]
    if not rows:
        xlsx.data_row(ws, r, ["-"] * ncols)
        return r + 1
    for n, it in enumerate(rows, 1):
        vals = ([n] if numbered else []) + [it.get(k, "") for k in keys]
        xlsx.data_row(ws, r, vals)
        r += 1
    return r
