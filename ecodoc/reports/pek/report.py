def _tot(p) -> Decimal:
    return D(p.mass_norm) + D(p.mass_limit) + D(p.mass_over)


def _names(values) -> list[str]:
    """Уникальные непустые наименования в порядке появления (перечни ЗВ
    таблиц 2.1 / 2.3)."""
    out: list[str] = []
    for v in values or []:
        name = str(v.get("name", "") if isinstance(v, dict) else v or "").strip()
        if name and name not in out:
            out.append(name)
