"""Отчёт об организации и о результатах осуществления ПЭК.

ДЕЙСТВУЮЩАЯ форма — Приказ Минприроды России от 15.03.2024 № 173 (в ред.
Приказа № 262 от 12.05.2025, действует с 01.09.2024). Требования к программе
ПЭК и сроки представления отчёта (до 25 марта, электронно с УКЭП через ЛК
природопользователя) — Приказ Минприроды России от 18.02.2022 № 109.
Прежняя форма (Приказ № 261 от 14.06.2018) утратила силу с 01.09.2024.

Печатная форма — титул + 20 пронумерованных таблиц приказа:
  1.1–1.3 — общие сведения, технологии, лаборатории;
  2.1–2.6 — воздух (перечень ЗВ, контроль источников, наблюдения, квоты);
  3.1–3.4 — вода (учёт объёмов, наблюдения за водными объектами, створы,
            очистные сооружения — по № 173 очистные это таблица 3.4);
  4.1–4.3 — отходы (мониторинг ОРО, движение отходов по 21 графе,
            контрагенты по 12 графам);
  5.1–5.2 — побочные продукты производства (5.2 — получатели, ред. № 262);
  6.1–6.2 — искусственные грунты из органической части ТКО (ред. № 262).
Составы граф сверены с принятым отчётом пользователя (ф. № 261) и текстом
№ 173; незаполненные таблицы печатаются с шапкой, строкой нумерации граф
и прочерками — как в принятых отчётах. XML самоописательный: официальной
XSD у формы нет, отчёт подаётся через ЛК РПН заполнением или прикреплением
печатной формы.

Полностью автоматическая сборка из ReportContext:
  * общие сведения        — organization + objects;
  * выбросы (раздел 2)    — ctx.pollutants (medium=air) + extra['emission_sources'];
  * сбросы (раздел 3)     — ctx.pollutants (medium=water) + extra['water'];
  * отходы (раздел 4)     — ctx.wastes (вся разбивка граф 4.2 уже в WasteFlow)
                            + extra['waste_receivers'] (таблица 4.3);
  * ППП / искусственные грунты — extra['ppp'] / ['ppp_receivers'] /
                            ['artificial_soil'] / ['soil_receivers'];
  * сведения о программе ПЭК и результаты наблюдений — ctx.extra['pek'].

Ключи ctx.extra['pek'] (всё необязательно; нет данных — в таблице прочерк и
предупреждение в validate(), ничего не выдумывается):
    program_number, program_date   — реквизиты программы ПЭК;
    responsible                    — кто отвечает за ПЭК (таблица 1.1, стр. 4);
    copy_no, executor_position, executor_name, place — титул;
    technologies  (1.2) [{workshop_no, workshop, technology, bat}];
    labs          (1.3) [{name, address, certificate}]; старый одностроковый
                        ключ lab «ООО Лаб (RA.RU.21XX)» разбирается на
                        наименование и реквизиты аттестата;
    air_controlled (2.1) [str] — перечень ЗВ плана-графика контроля источников;
                        если нет — берутся вещества из extra.emission_sources,
                        иначе ctx.pollutants (воздух);
    air_observed   (2.3) [str] — перечень ЗВ плана-графика наблюдений за
                        атмосферным воздухом; если нет — вещества из
                        air_monitoring;
    air_monitoring (2.4) [{point_no, address, coords, substance, months,
                        period, violations, avg_conc, max_conc, pdk_mr,
                        pdk_ss, exceed_le10, exceed_gt10, note}];
                        старый ключ results [{point, substance, plan, fact,
                        exceed}] печатается там же (пункт/вещество/
                        периодичность, факт и превышение — в примечании);
    quotas (2.5), quota_actions (2.6);
    water_letters  (3.1) [{letter, authority, intake_pollutants_t}] —
                        реквизиты письма в Росводресурсы, террорган,
                        количество ЗВ в забранной воде, т/год;
    water_observation (3.2) [{letter, authority}] — реквизиты письма о
                        наблюдениях за водными объектами и их ВОЗ, террорган
                        Росводресурсов;
    surface_water (3.3), treatment (3.4), oro_monitoring (4.1).
Результаты контроля источников выбросов (2.2) — extra.emission_sources
[{number, name, workshop_no, workshop, pollutants: [{name, g_s_norm, g_s,
date, exceed_cases, note}]}]: превышение в раз (гр. 9) считается как
г/с факт / г/с норматив.
ППП (5.1) — extra.ppp [{name, okpd2, period, start, formed, used_own,
raw_product_name, raw_product_docs, raw_product_qty, cons_product_name,
cons_product_docs, cons_product_qty, transferred_raw, transferred_product,
end, consumer_product, application}]; ИГ (6.1) — extra.artificial_soil —
те же ключи + produced (вместо formed) и standards (реквизиты документов
по стандартизации).

Протоколы КХА/биотестирования подгружаются как исходники (analyze) и
перечисляются в реестре результатов.
"""
from __future__ import annotations

from decimal import Decimal
from pathlib import Path

from lxml import etree
from openpyxl.styles import Font
from openpyxl.utils import get_column_letter

from ecodoc.core.models import Issue, Medium, ReportContext
