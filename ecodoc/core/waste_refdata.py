def _words(s: str) -> set[str]:
    return {w for w in re.findall(r"[а-яёa-z0-9]+", (s or "").lower().replace("ё", "е"))
            if len(w) > 3 and w not in _STOP}


_FOREIGN_UNITS = ("мг/м3", "мг/м³", "мг/куб", "г/с", "г/сек", "т/год", "мг/дм3",
                  "мг/дм³", "мг/л", "г/л", "мкг/м3", "мкг/м³", "мг/ч", "кг/ч",
                  "дба", "дб", "ед. ph", "ед.ph", "клеток", "экз/", "кое")


def protocol_units_ok(lab: dict) -> bool:
    """Единицы результатов протокола — состав отхода (%, мг/кг, г/кг, доли),
    а не выбросы (мг/м³, г/с, т/год), вода (мг/дм³, мг/л), шум (дБА),
    микробиология. Протокол без единиц считается пригодным."""
    units = [str(s.get("unit") or "").lower().replace(" ", "")
             for s in (lab.get("substances") or []) if isinstance(s, dict)]
    units = [u for u in units if u]
    if not units:
        return True
    foreign = sum(1 for u in units if any(f in u for f in _FOREIGN_UNITS))
    return foreign * 2 < len(units)


def protocol_matches_waste(lab: dict, fkko, name: str = "",
                           kinds: tuple | None = None) -> bool:
    """Это протокол СОСТАВА именно этого отхода: вид исследования — КХА /
    морфологический / компонентный состав, а объект — сам отход (совпадает
    код ФККО или наименование целиком либо по основе слов). Протоколы
    воздуха/воды/почвы с похожим обрывком имени — не подходят."""
    if not isinstance(lab, dict):
        return False
    kind = str(lab.get("kind") or "").lower()
    if not any(k.lower() in kind for k in (kinds or _COMPOSITION_KINDS)):
        return False
    if not protocol_units_ok(lab):
        return False
    code = norm_fkko(fkko or "")
    tcode = norm_fkko(lab.get("fkko") or "")
    target = " ".join(str(lab.get(k) or "") for k in ("object", "waste", "name"))
    tlow = target.lower().replace("ё", "е")
    if code and tcode == code:
        return True
    if code and len(code) == 11 and re.sub(r"\D", "", target).find(code) >= 0:
        return True
    n = (name or "").strip().lower().replace("ё", "е")
    if not n or len(n) < 8:
        return False
    if n[:60] in tlow:
        return True
    if any(k in tlow for k in ("атмосферн", "воздух", "сточн", "почв", "вода ",
                               "воды ", "грунтов", "шум")) and "отход" not in tlow:
        return False
    nw, tw = _words(n), _words(target)
    if not nw or not tw:
        return False
    return len(nw & tw) / len(nw) >= 0.6


