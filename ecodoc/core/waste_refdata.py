def _key(s: str) -> str:
    s = (s or "").lower().replace("ё", "е")
    s = re.sub(r"[()«»\"'’]", " ", s)
    return re.sub(r"\s+", " ", s).strip()


def _stems(s: str) -> tuple[str, ...]:
    return tuple(sorted(w[:5] for w in re.findall(r"[а-яa-z0-9]+", _key(s))
                        if len(w) > 2))


_ALIAS_INDEX: dict[str, str] = {}
_STEM_INDEX: dict[tuple, str] = {}
for _name, _rec in WI_TABLE.items():
    for _a in [_name] + _rec["aliases"]:
        _ALIAS_INDEX.setdefault(_key(_a), _name)
        st = _stems(_a)
        if st:
            _STEM_INDEX.setdefault(st, _name)


def wi_for(component: str) -> tuple[float | None, str, str]:
    """(Wi, источник, каноническое имя) для компонента по справочнику;
    (None, '', '') — компонента в справочнике нет (Wi надо взять из БДО)."""
    raw = _key(component)
    if not raw:
        return None, "", ""
    # «прочие/неидентифицированные» — Wi не назначаем
    if raw.startswith("проч") or "неидентиф" in raw or "неклассиф" in raw:
        return None, "", ""
    cand = [raw] + [p.strip() for p in re.split(r"[(),;/]", _key(component))
                    if p.strip()]
    for c in cand:
        hit = _ALIAS_INDEX.get(c)
        if hit:
            return WI_TABLE[hit]["wi"], WI_TABLE[hit]["source"], hit
    for c in cand:
        st = _stems(c)
        hit = _STEM_INDEX.get(st) if st else None
        if hit:
            return WI_TABLE[hit]["wi"], WI_TABLE[hit]["source"], hit
    # по вхождению длинного алиаса в наименование (≥ 5 символов)
    best = None
    for alias, name in _ALIAS_INDEX.items():
        if len(alias) >= 5 and re.search(r"(^|\W)" + re.escape(alias) + r"(\W|$)", raw):
            if best is None or len(alias) > len(best[0]):
                best = (alias, name)
    if best:
        name = best[1]
        return WI_TABLE[name]["wi"], WI_TABLE[name]["source"], name
    return None, "", ""


def wi_table_rows() -> list[dict]:
    """Справочник Wi для показа/выбора в интерфейсе."""
    return [{"name": n, "wi": r["wi"], "source": r["source"],
             "aliases": list(r["aliases"])} for n, r in WI_TABLE.items()]
